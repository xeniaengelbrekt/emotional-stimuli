/* ============================================================
   lexeme.js — эвристика «слова одного корня / словоформы одного слова».
   Без словарей и морфологии: слова считаются родственными, если у них
   общее начало не короче 4 букв и различаются не более чем двумя
   последними буквами («тактика — тактики», «звезда — звезды», «идеал — идеалы»).
   Эвристика намеренно с запасом: лучше не поставить рядом лишнюю пару слов
   (например, «правда — право»), чем показать словоформы одного слова в одном стимуле.
   ============================================================ */

const norm = (s) => String(s ?? '').toLocaleLowerCase('ru').replace(/ё/g, 'е').replace(/[^\p{L}\p{N}]/gu, '');

export function sameLexeme(a, b) {
  const x = norm(a); const y = norm(b);
  if (!x || !y) return false;
  if (x === y) return true;
  let k = 0;
  while (k < x.length && k < y.length && x[k] === y[k]) k++;
  return k >= 4 && k >= Math.min(x.length, y.length) - 2;
}

/** Есть ли среди `list` слово, родственное `word`. Элементы — строки или объекты со свойством `word`. */
export const hasRelative = (word, list) => list.some((x) => sameLexeme(word, typeof x === 'string' ? x : x.word));
